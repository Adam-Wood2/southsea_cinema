class Movie {
  final String id;
  final String name;
  final String description;
  final double price;
  final String date;
  final String time;
  final int length;
  final String imagePath;

  const Movie({
    required this.id,
    required this.name,
    required this.description,
    required this.price,
    required this.date,
    required this.time,
    required this.length,
    required this.imagePath
  })
}
